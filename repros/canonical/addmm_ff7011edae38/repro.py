_repro_version = 3


class Repro(torch.nn.Module):
    def forward(self, input_2, input_3, input_4):
        permute_default = torch.ops.aten.permute.default(input_2, [1, 0]);  input_2 = None
        addmm_default = torch.ops.aten.addmm.default(input_3, input_4, permute_default, beta = 1, alpha = 1);  input_3 = input_4 = permute_default = None
        return (addmm_default,)


def make_inputs(shape_config=None):
    if shape_config is None:
        shape_config = default_shape_config(__file__)
    if shape_config is None:
        raise RuntimeError("No input points in the sibling shapes.json")
    return make_inputs_from_config(shape_config)


if __name__ == "__main__":
    benchmark_repro(__file__, Repro, make_inputs)
